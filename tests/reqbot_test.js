const {JSDOM} = require('jsdom'); const fs = require('fs');
let html = fs.readFileSync(require('path').join(__dirname, '..', 'index.html'), 'utf8').replace(/<script src=[^>]+><\/script>/, '').replace(/<link[^>]+>/g, '');
const dom = new JSDOM(html, {url:'https://x.org/', runScripts:'dangerously', pretendToBeVisual:true, beforeParse(w){ w.fetch = async () => ({ok:false, json: async () => ({})}); }});
const w = dom.window, d = w.document, $ = s => d.querySelector(s), ev = c => w.eval(c);
w.addEventListener('error', e => console.log('ERR', e.message));
let fails = 0; const check = (ok, msg) => { console.log((ok ? 'OK     ' : 'FEHLER ') + msg); if(!ok) fails++; };
const wait = ms => new Promise(r => setTimeout(r, ms));
const C = (n, type, o, x = {}) => ev('newCard')({n, type, o, img:null, ...x});
const click = async t => { const b = [...d.querySelectorAll('#modalBox button')].find(b => b.textContent.trim().startsWith(t)); if(b){ b.click(); await wait(30); } return !!b; };
(async () => {
  $('#lName').value = 'Lukas'; $('#lSolo').click(); await wait(30); ev('closeModal()'); ev('LOOK.autoPay = false');
  ev('startBot("Test", "Test", Array(30).fill(0).map(() => ({n:"Island", type:"Basic Land — Island", o:""})))'); ev('injectBot()');
  ev('BOT.hand = [newCard({n:"Island", type:"Basic Land — Island"}), newCard({n:"Tarmogoyf", type:"Creature — Lhurgoyf", mc:"{1}{G}", cmc:2, pw:4, tg:5}), newCard({n:"Brainstorm", type:"Instant", mc:"{U}", cmc:1})]; botChanged(); commit()'); await wait(30);
  const du = C('Duress', 'Sorcery', 'Target opponent reveals their hand. You choose a noncreature, nonland card from it. That player discards that card.', {mc:'{B}', cmc:1});
  ev('S').hand.push(du); ev('commit()');
  const p = ev('castSpell')(du.u); await wait(40);
  const cards = [...d.querySelectorAll('#modalBox .card')];
  check(cards.length === 3 && cards.filter(e => e.style.opacity !== '0.4').length === 1, `Duress: KI-Hand sichtbar, nur Brainstorm wählbar`);
  cards.find(e => /Brainstorm/.test(e.textContent)).click(); await p; await wait(30);
  check(ev('BOT.gy.some(c => c.n === "Brainstorm")') && ev('BOT.hand.length') === 2, 'KI wirft Brainstorm ab');
  const hy = C('Hymn to Tourach', 'Sorcery', 'Target player discards two cards at random.', {mc:'{B}{B}', cmc:2});
  ev('S').hand.push(hy); ev('commit()');
  const ph = ev('castSpell')(hy.u); await wait(30); await click('KI'); await ph; await wait(30);
  check(ev('BOT.hand.length') === 0 && ev('BOT.gy.length') === 3, 'Hymn: KI wirft 2 zufällig ab');
  ev('BOT.bf.push(newCard({n:"Goblin", type:"Token Creature — Goblin", pw:1, tg:1, tok:true}), newCard({n:"Tarmogoyf", type:"Creature — Lhurgoyf", pw:4, tg:5})); botChanged()');
  const ed = C('Diabolic Edict', 'Instant', 'Target player sacrifices a creature of their choice.', {mc:'{1}{B}', cmc:2});
  ev('S').hand.push(ed); ev('commit()');
  const pe = ev('castSpell')(ed.u); await wait(30); await click('KI'); await pe; await wait(30);
  check(ev('BOT.gy.some(c => c.n === "Goblin")') || !ev('BOT.bf.some(c => c.n === "Goblin")'), 'Edict: KI opfert den Goblin-Token, nicht den Goyf');
  console.log(fails ? `\n${fails} FEHLER` : '\nALLES OK'); process.exit(0);
})();
