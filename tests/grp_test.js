const {JSDOM} = require('jsdom'); const fs = require('fs');
let html = fs.readFileSync(require('path').join(__dirname, '..', 'index.html'), 'utf8').replace(/<script src=[^>]+><\/script>/, '').replace(/<link[^>]+>/g, '');
const dom = new JSDOM(html, {url:'https://x.org/', runScripts:'dangerously', pretendToBeVisual:true, beforeParse(w){ w.fetch = async () => ({ok:false, json: async () => ({})}); }});
const w = dom.window, d = w.document, $ = s => d.querySelector(s), ev = c => w.eval(c);
w.addEventListener('error', e => console.log('ERR', e.message));
let fails = 0; const check = (ok, msg) => { console.log((ok ? 'OK     ' : 'FEHLER ') + msg); if(!ok) fails++; };
const wait = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  $('#lName').value = 'Lukas'; $('#lSolo').click(); await wait(30); ev('closeModal()');
  const S = ev('S');
  ev('for(let i=0;i<5;i++) S.bf.push(newCard({...LOCAL_TOKENS.food, tok:true})); for(let i=0;i<2;i++) S.bf.push(newCard({...LOCAL_TOKENS.treasure, tok:true})); S.bf.push(newCard({n:"Bear", type:"Creature — Bear", pw:2, tg:2})); commit()');
  const cards = () => [...d.querySelectorAll('#myField .card')];
  check(cards().length === 3, `3 Stapel/Karten statt 8 (${cards().length})`);
  const badge = () => cards()[0].querySelector('.stackbadge').textContent;
  check(/5×/.test(badge()) && !/getappt/.test(badge()), `Food: «${badge()}»`);
  const foods = S.bf.filter(c => c.n === 'Food');
  ev('toggleTap')(foods[0]); await wait(10);
  check(/5×2 getappt|5×1 getappt/.test(badge()), `einen getappt: «${badge()}»`);
  const items = ev('groupMenu')(foods);
  items.find(i => /^Alle \d+ tappen/.test(i.l || '')).f(); await wait(10);
  check(foods.every(f => f.tap) && /5 getappt/.test(badge()), `alle getappt: «${badge()}»`);
  check(ev('groupMenu')(foods).some(i => /Fähigkeit: \{2\}/.test(i.l || '')), 'Gruppenmenü enthält die Food-Fähigkeit');
  ev('groupMenu')(foods).find(i => /^Alle \d+ enttappen/.test(i.l || '')).f(); await wait(10);
  ev('groupMenu')(foods).find(i => /vom Stapel lösen/.test(i.l || '')).f(); await wait(10);
  check(cards().length === 4 && /4×/.test(badge()), `einer gelöst: ${cards().length} Elemente, «${badge()}»`);
  ev('groupMenu')(S.bf.filter(c => c.n === 'Treasure')).find(i => /Einen opfern/.test(i.l || '')).f(); await wait(10);
  check(S.bf.filter(c => c.n === 'Treasure').length === 1 && cards().length === 4, 'Treasure: einer geopfert, der letzte ohne Stapel');
  ev('LOOK.groupTokens = false; commit()'); await wait(10);
  check(cards().length === 7, `Stapeln aus: alle einzeln (${cards().length})`);
  console.log(fails ? `\n${fails} FEHLER` : '\nALLES OK'); process.exit(0);
})();
